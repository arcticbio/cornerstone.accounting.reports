def _full_set(sid: str, at: float, prop: str, period: str, *, ds: bool = True) -> list[Act]:
    label = "Sep 2026" if period == SEP else "Oct 2026"
    n = NAMES[prop]
    acts = [
        Act(
            at, sid, PM_WHO[prop], "upload", prop, period, PM, "pm", f"{n} Owner Report {label}.pdf"
        ),
        Act(
            at, sid, ACCOUNTING, "upload", prop, period, BS, "bs", f"{n} Balance Sheet {label}.pdf"
        ),
        Act(
            at + 0.5, sid, ACCOUNTING, "upload", prop, period, PL, "pl", f"{n} P&L YTD {label}.pdf"
        ),
    ]
    if ds:
        acts.append(
            Act(
                at + 0.5,
                sid,
                ACCOUNTING,
                "upload",
                prop,
                period,
                DS,
                "ds",
                f"{n} Distribution Schedule {label}.pdf",
            )
        )
    return acts


